"""
Builds the modeling album from the photo shoot.
  python scripts/model/ingest.py <folder with the DSC*.png exports>
Writes web webp files to public/creative/model/, the square cover to
public/creative/covers/modeling.webp, the arc sleeve to
public/creative/works/sleeve-modeling.webp and lib/creative/model.ts.
Needs Pillow and ffmpeg on PATH.
"""
import os, subprocess, sys
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.expanduser('~'), 'Downloads')
OUT = os.path.join(ROOT, 'public', 'creative', 'model')
os.makedirs(OUT, exist_ok=True)

# id, group, title
SHOTS = [
    ('08842', 'noir', 'Frontal'),
    ('08822-Edit', 'noir', 'Standing'),
    ('08814-Edit', 'noir', 'Seated'),
    ('08842-Edit', 'noir', 'Frontal, mono'),
    ('08844', 'noir', 'Hand to lip'),
    ('08847', 'noir', 'Look away'),
    ('08858', 'noir', 'Hands and rings'),
    ('08861', 'noir', 'Lean in'),
    ('08865', 'noir', 'Lean in, close'),
    ('08898', 'noir', 'Portrait'),
    ('08906', 'noir', 'Temple'),
    ('08897-Edit', 'noir', 'Mono portrait'),
    ('08839', 'noir', 'Shadow'),
    ('08883', 'profile', 'Profile, up'),
    ('08891', 'profile', 'Profile'),
    ('09054', 'paper', 'Seated, mono'),
    ('09057', 'paper', 'White, open'),
    ('09060', 'paper', 'White, seated'),
    ('09067', 'paper', 'White, low'),
    ('09073', 'paper', 'White, still'),
    ('09074', 'paper', 'White, head down'),
    ('09075', 'paper', 'White, curls'),
    ('09077', 'paper', 'White, mono'),
    ('08829', 'detail', 'The cross'),
    ('08853', 'detail', 'Rings and chain'),
    ('08856', 'detail', 'Chain, close'),
    ('09017', 'lifestyle', 'Hair care, throw'),
    ('09025', 'lifestyle', 'Hair care, catch'),
    ('08924', 'lifestyle', 'Hair care, hold'),
]

rows = []
for sid, grp, title in SHOTS:
    im = Image.open(os.path.join(SRC, f'DSC{sid}.png')).convert('RGB')
    w, h = im.size
    k = 1600 / max(w, h)
    im2 = im.resize((round(w * k), round(h * k)), Image.LANCZOS)
    im2.save(os.path.join(OUT, f'{sid.lower()}.webp'), 'WEBP', quality=80, method=5)
    rows.append((sid.lower(), grp, title, round(w / h, 4)))
    if sid == '08842':
        # square cover: crop around the face and chest
        cw = int(w * 0.9)
        left = (w - cw) // 2
        top = int(h * 0.08)
        sq = im.crop((left, top, left + cw, top + cw)).resize((1600, 1600), Image.LANCZOS)
        sq.save(os.path.join(ROOT, 'public', 'creative', 'covers', 'modeling.webp'), 'WEBP', quality=84, method=5)

# the arc sleeve: blurred backdrop, the cover, a vinyl peeking out
src = os.path.join(ROOT, 'public', 'creative', 'covers', 'modeling.webp')
dst = os.path.join(ROOT, 'public', 'creative', 'works', 'sleeve-modeling.webp')
fc = (
    "[0:v]split=3[bg][fg][vn];"
    "[bg]scale=1600:1600,crop=1600:1000,boxblur=40:6,eq=brightness=-0.22:saturation=1.25[b];"
    "[vn]scale=760:760,format=rgba,geq=r='20+10*sin(hypot(X-380,Y-380)*0.9)':g='20+10*sin(hypot(X-380,Y-380)*0.9)':b='22+10*sin(hypot(X-380,Y-380)*0.9)':a='if(lt(hypot(X-380,Y-380),378),255,0)'[v];"
    "[fg]scale=800:800[c];"
    "[b][v]overlay=770:120[t1];"
    "[t1][c]overlay=300:100[out]"
)
subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', '-i', src, '-filter_complex', fc, '-map', '[out]', '-frames:v', '1', '-c:v', 'libwebp', '-quality', '82', dst], check=True)

ts = ["/** Generated by scripts/model/ingest.py from the photo shoot. */",
      "export type ModelGroup = 'noir' | 'profile' | 'paper' | 'detail' | 'lifestyle'",
      "export type ModelShot = { id: string; group: ModelGroup; title: string; src: string; ratio: number }",
      "",
      "export const MODEL_SHOTS: ModelShot[] = ["]
for sid, grp, title, ratio in rows:
    ts.append(f"  {{ id: 'm{sid}', group: '{grp}', title: '{title}', src: '/creative/model/{sid}.webp', ratio: {ratio} }},")
ts.append(']')
open(os.path.join(ROOT, 'lib', 'creative', 'model.ts'), 'w', encoding='utf-8', newline='\n').write('\n'.join(ts) + '\n')
tot = sum(os.path.getsize(os.path.join(OUT, f)) for f in os.listdir(OUT))
print(len(rows), 'shots', tot // 1024, 'KB')
